@bp.post("/login")
def login_post():
    form = request.form
    if rate_limited():
        log.warning("admin: login refused, rate limit")
        return render_template(
            "login.html", csrf=csrf_token(),
            error="Too many attempts. Try again later."), 429

    if not _csrf_ok(form):
        # Not counted as a failed password: a missing token is usually a stale
        # tab or a browser that dropped the cookie, and burning the attempt
        # budget on it would lock the owner out of their own dashboard.
        return render_template(
            "login.html", csrf=csrf_token(),
            error="That form expired. Try again."), 400

    if not check_login(form.get("username"), form.get("password")):
        record_failure()
        # No username, no address, nothing about the attempt. The house rule
        # about logs does not have an exception for the login page.
        log.warning("admin: login failed")
        return render_template(
            "login.html", csrf=csrf_token(),
            error="Wrong username or password."), 401

    clear_failures()
    _start_session()
    return redirect(url_for("admin.index"))


