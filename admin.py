"""Admin dashboard — one login, and a read-only window onto the funnels.

Owns: `/admin` (login, overview, funnel detail, A/B panel) and `/admin/api/*`.

Two things this file will not do, and both are load-bearing:

**It never writes.** Every statement it reaches goes through analytics.py, and
every statement in analytics.py is a SELECT. There is no form here that
changes a funnel, no button that refunds a purchase and no endpoint that
takes a POST body of anything but a password. A dashboard that can only look
is a dashboard that can be opened on a phone on a train without care.

**Its pages are not files under static/.** Everything in `static/` is served
by the web server and cached by Cloudflare with no worker in the loop, which
is exactly what makes the funnel fast and exactly what would make an admin
page public. So these pages are rendered here, behind the session check, and
answered `private, no-store`.

The credentials live in `.env` (ADMIN_USER, ADMIN_PASSWORD_HASH) and nowhere
else. Missing, the whole blueprint answers 503 and says so — never an open
dashboard, and never a server that refuses to boot over it.
"""

