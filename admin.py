def _json_error(exc, what):
    log.exception("admin: %s failed", what)
    return jsonify({"error": "query_failed",
                    "message": "The database did not answer. %s" % what}), 503


def _guarded(what):
    """Wrap a route so a database that is down is a sentence, not a stack.

    This dashboard reads a database over a network from a page somebody opens
    on a phone. When that fails the useful answer is "the database did not
    answer", not a 500 whose body is an HTML error page the JSON caller cannot
    parse.
    """
    def wrap(view):
        @functools.wraps(view)
        def inner(*args, **kwargs):
            try:
                return view(*args, **kwargs)
            except Exception as exc:      # noqa: BLE001 - reported, not hidden
                if _wants_json():
                    return _json_error(exc, what)
                log.exception("admin: %s failed", what)
                return render_template("unconfigured.html",
                                       message="The database did not answer. "
                                               "Try again in a moment."), 503
        return inner
    return wrap


